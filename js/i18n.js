export const dictionaries = Object.freeze({
  tr: Object.freeze(tr),
  en: Object.freeze(Object.fromEntries(Object.keys(tr).map(key => [key, ''])))
});
let language = 'tr';
export function getLanguage() { return language; }
export function t(key, params = {}) {
  const text = dictionaries[language][key] || dictionaries.tr[key] || key;
  return text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
}
export function setLanguage(value) {
  if (!Object.hasOwn(dictionaries, value)) throw new RangeError('Geçersiz dil.');
  language = value;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = value;
    applyTranslations();
    document.dispatchEvent(new CustomEvent('languagechange', { detail: { language: value } }));
  }
}
export function applyTranslations(root = document) {
  const nodes = [...root.querySelectorAll('[data-i18n], [data-i18n-placeholder], [data-i18n-title], [data-i18n-aria-label], [data-i18n-alt]')];
  if (root.nodeType === 1) nodes.unshift(root);
  for (const node of nodes) {
    if (node.dataset.i18n) node.textContent = t(node.dataset.i18n);
    for (const attribute of ['placeholder', 'title', 'aria-label', 'alt']) {
      const key = node.getAttribute(`data-i18n-${attribute}`);
      if (key) node.setAttribute(attribute, t(key));
    }
  }
}
